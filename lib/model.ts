// The token radar's model ("radar-2"): one snapshot of the protocol universe in, one ranked
// board out.
//
// The board covers every slug in the snapshot's watchlist (the floor, never a ceiling) and adds
// the pre-token protocols below the watchlist floor that pass the same exclusion rules the house
// used for the watchlist, as far as the snapshot's own ten fields let the entry check them: no
// CEX, Bridge, Canonical Bridge, Liquid Staking, Liquid Restaking or Restaked BTC category, no
// versioned name, no whole word wrapped/staked/staking, no exchange-name prefix. A protocol is
// pre-token when its index entry records no token (no market cap, no CoinGecko id, no symbol);
// the snapshot's live-token protocols are kept apart and shown as the market's own values, never
// mixed into the ranked board.
//
// Implied value is priced from live peers, never from a hardcoded multiple:
//
//   multiple   = median(mcap_usd / tvl_usd) of the live protocols in the same category
//                (at least 3 comps), else the global median of every live multiple;
//                capped at 2.0x and floored at 0.01x, so one thin market never prices a
//                whole category and no category is ever priced at zero.
//   growth     = clamp(change_7d, -60, 120) per cent
//   growthMult = 1 + (growth / 100) x GROWTH_WEIGHT
//   maturity   = 0.7 + min(age_days, 1095) / 1095 x 0.3   (age_days unknown: the snapshot's
//                median listed age, computed at runtime)
//   implied    = max(1, round(tvl_usd x multiple x growthMult x maturity))
//
// The constants are the model's, stated in the dashboard and shown per row with the multiple's
// comp count and source. No protocol name is ever special-cased: the same function scores every
// row, and the multiples table is computed from the snapshot on every run.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

/** The model's constants, as the dashboard states them. */
export interface ModelConstants {
  growth_weight: number;
  growth_floor: number;
  growth_cap: number;
  maturity_floor: number;
  maturity_range: number;
  maturity_days: number;
  multiple_cap: number;
  multiple_floor: number;
  min_category_comps: number;
}

export const MODEL: ModelConstants = {
  growth_weight: 0.5,
  growth_floor: -60,
  growth_cap: 120,
  maturity_floor: 0.7,
  maturity_range: 0.3,
  maturity_days: 1095,
  multiple_cap: 2.0,
  multiple_floor: 0.01,
  min_category_comps: 3,
};

/** The model's version label: the dashboard names it and the rules quote it. */
export const MODEL_VERSION = 'radar-2';

/** How many live-token protocols the Live token view carries, by market cap. */
export const LIVE_ROWS = 24;

/** One category's comparable multiple, as the dashboard's comparables table shows it. */
export interface CategoryMultiple {
  category: string;
  multiple: number;
  comps: number;
  source: 'category' | 'global';
}

/** The multiples table: every live protocol's market-cap-per-TVL, summarised. */
export interface MultiplesTable {
  global_multiple: number;
  global_comps: number;
  by_category: CategoryMultiple[];
}

/** Why the snapshot is not one this model can score. */
export class SnapshotError extends Error {
  constructor(message: string) {
    super(message);
    this.name = 'SnapshotError';
  }
}

const DAY_MS = 86_400_000;

/** A finite number, else `fallback`. */
function finite(value: unknown, fallback: number): number {
  return typeof value === 'number' && Number.isFinite(value) ? value : fallback;
}

/** The median of a non-empty list of numbers; 0 when it is empty. */
export function median(values: number[]): number {
  if (values.length === 0) return 0;
  const sorted = [...values].sort((a, b) => a - b);
  const mid = Math.floor(sorted.length / 2);
  return sorted.length % 2 === 1 ? sorted[mid]! : (sorted[mid - 1]! + sorted[mid]!) / 2;
}

/** A whole day count from `from` to `to`, clamped at zero; null when either date is absent or bad. */
export function ageDays(asOf: string, listedAt: string | null): number | null {
  if (listedAt === null) return null;
  const a = Date.parse(`${asOf}T00:00:00Z`);
  const b = Date.parse(`${listedAt}T00:00:00Z`);
  if (!Number.isFinite(a) || !Number.isFinite(b)) return null;
  return Math.max(0, Math.floor((a - b) / DAY_MS));
}

/** The median age, in days, of the snapshot's protocols that carry a listed date. */
export function medianAge(snapshot: Snapshot): number {
  const ages = snapshot.protocols
    .map((p) => ageDays(snapshot.as_of, p.listed_at))
    .filter((a): a is number => a !== null);
  return Math.round(median(ages));
}

/** Whether a protocol records no token at all. */
export function isPreToken(p: SnapshotProtocol): boolean {
  return p.mcap_usd === null && p.gecko_id === null && p.symbol === null;
}

/** DefiLlama's version-marker rule: a name ending in a release is a pool of another protocol. */
const VERSIONED = /\s(V\d+(\.\d+)?|v\d+(\.\d+)?|\d+\.\d+)$/;
/** A whole word wrapped, staked or staking in a name: a wrapped or staked product. */
const WRAPPED_WORD = /\b(wrapped|staked|staking)\b/i;
/** An exchange's name at the start of a protocol's name. */
const EXCHANGE_PREFIX =
  /^(Binance|Coinbase|Bybit|Kraken|Bitget|OKX|Bitfinex|Gemini)\b/;
/** Categories the watchlist rule leaves out: a wrapped, staked or bridged product of a token
    that already trades, or an exchange itself. */
const EXCLUDED_CATEGORIES = new Set([
  'Bridge',
  'Canonical Bridge',
  'Liquid Staking',
  'Liquid Restaking',
  'Restaked BTC',
  'CEX',
]);

/** Whether a protocol is one the board may rank: pre-token, not an exchange, not a wrapped,
    staked or bridged product, not a versioned pool. The watchlist's own slugs always pass:
    the house already applied its full rule (parent protocol included) to them. */
export function isRankable(p: SnapshotProtocol, onWatchlist: boolean): boolean {
  if (!isPreToken(p)) return false;
  if (onWatchlist) return true;
  if (p.category !== null && EXCLUDED_CATEGORIES.has(p.category)) return false;
  if (VERSIONED.test(p.name)) return false;
  if (WRAPPED_WORD.test(p.name)) return false;
  if (EXCHANGE_PREFIX.test(p.name)) return false;
  return true;
}

/**
 * The comparables table: the median market-cap-per-TVL of the live protocols, per category
 * where at least `min_category_comps` trade, and the global median over every live protocol.
 * A live protocol is one that records a token with a market cap on positive TVL.
 */
export function buildMultiples(snapshot: Snapshot, model: ModelConstants = MODEL): MultiplesTable {
  const byCategory = new Map<string, number[]>();
  const all: number[] = [];
  for (const p of snapshot.protocols) {
    if (p.mcap_usd === null || p.mcap_usd <= 0 || p.tvl_usd <= 0) continue;
    const multiple = p.mcap_usd / p.tvl_usd;
    if (!Number.isFinite(multiple) || multiple <= 0) continue;
    all.push(multiple);
    const key = p.category ?? 'Other';
    const list = byCategory.get(key);
    if (list === undefined) byCategory.set(key, [multiple]);
    else list.push(multiple);
  }
  const global = Math.min(model.multiple_cap, Math.max(model.multiple_floor, median(all)));
  const rows: CategoryMultiple[] = [];
  for (const [category, values] of [...byCategory.entries()].sort((a, b) => (a[0] < b[0] ? -1 : 1))) {
    if (values.length < model.min_category_comps) continue;
    rows.push({
      category,
      multiple: Math.min(model.multiple_cap, Math.max(model.multiple_floor, median(values))),
      comps: values.length,
      source: 'category',
    });
  }
  return { global_multiple: global, global_comps: all.length, by_category: rows };
}

/** The multiple one protocol is priced at, with where it came from. */
export function multipleFor(
  category: string | null,
  table: MultiplesTable,
): { multiple: number; comps: number; source: 'category' | 'global' } {
  const key = category ?? 'Other';
  const hit = table.by_category.find((r) => r.category === key);
  if (hit !== undefined) return { multiple: hit.multiple, comps: hit.comps, source: 'category' };
  return { multiple: table.global_multiple, comps: table.global_comps, source: 'global' };
}

/** The three multipliers and the implied value one protocol gets under `model`. */
export function impliedValue(
  protocol: SnapshotProtocol,
  asOf: string,
  table: MultiplesTable,
  unknownAgeDays: number,
  model: ModelConstants = MODEL,
): {
  implied: number;
  multiple: number;
  multipleComps: number;
  multipleSource: 'category' | 'global';
  growthPct: number;
  growthMult: number;
  maturityMult: number;
  age: number | null;
} {
  const age = ageDays(asOf, protocol.listed_at);
  const { multiple, comps, source } = multipleFor(protocol.category, table);
  // The multiple the board prints is the multiple the board prices with: round it first, so the
  // dashboard's recompute of the row lands on the same implied value board.json carries.
  const multipleUsed = Math.round(multiple * 1e4) / 1e4;
  const rawGrowth = finite(protocol.change_7d, 0);
  const growthPct = Math.min(model.growth_cap, Math.max(model.growth_floor, rawGrowth));
  const growthMult = 1 + (growthPct / 100) * model.growth_weight;
  const ageForModel = age ?? unknownAgeDays;
  const maturityMult =
    model.maturity_floor +
    (Math.min(Math.max(ageForModel, 0), model.maturity_days) / model.maturity_days) * model.maturity_range;
  const implied = Math.max(1, Math.round(protocol.tvl_usd * multipleUsed * growthMult * maturityMult));
  return { implied, multiple: multipleUsed, multipleComps: comps, multipleSource: source, growthPct, growthMult, maturityMult, age };
}

